#!/usr/bin/env python3
"""Generate package-contained Astrobyte policy from its canonical profile."""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
from typing import Any

try:
    from scripts.profile import load_object, validate_git_identity
except ModuleNotFoundError:  # Direct script execution.
    from profile import load_object, validate_git_identity  # type: ignore[no-redef]


REPO_ROOT = Path(__file__).resolve().parents[1]
PORTABLE_DEFAULTS = (
    "autonomy_preset", "communication_style", "explanation_level", "delivery_mode",
    "git_workflow", "issue_tracker", "skill_update_policy", "ci_validation",
)
GENERATED_HEADER = "<!-- Generated by scripts/portable_profile.py; edit the canonical profile. -->\n\n"


def json_text(value: dict[str, Any]) -> str:
    return json.dumps(value, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def agreement_section(agreement: str, heading: str) -> str:
    marker = f"## {heading}\n"
    sections = agreement.split(marker)
    if len(sections) != 2:
        raise ValueError(f"Working agreement must contain exactly one {heading!r} section")
    body = sections[1].split("\n## ", 1)[0].strip()
    if not body:
        raise ValueError(f"Working agreement section {heading!r} is empty")
    return body


def resource_contents(root: Path = REPO_ROOT) -> dict[Path, str]:
    """Return deterministic relative package paths and their expected contents."""
    directory = root / "profiles" / "astrobyte"
    profile = load_object(directory / "profile.json")
    agreement_name = profile["working_agreement"]
    if not isinstance(agreement_name, str) or Path(agreement_name).name != agreement_name:
        raise ValueError("working_agreement must name a file in the baseline profile directory")
    agreement = (directory / agreement_name).read_text(encoding="utf-8")
    identity = profile["git_identity"]
    errors = validate_git_identity(identity, require_human=False)
    if errors:
        raise ValueError("Invalid baseline Git policy: " + "; ".join(errors))
    # Copy policy only. Human identities, machine registries and publication
    # settings never become package defaults, including unknown future fields.
    git_policy = {
        key: identity[key]
        for key in ("mode", "human_identity_source", "trailer_key", "verify_before_push")
    }
    git_policy["agents"] = {
        harness: {key: value[key] for key in ("name", "email")}
        for harness, value in identity["agents"].items()
    }
    portable = {
        "profile": profile["skill_profile"],
        "defaults": {key: profile["defaults"][key] for key in PORTABLE_DEFAULTS},
        "skills": {
            key: profile["skills"][key]
            for key in ("required", "require_independent_feedback")
        },
        "git_identity": git_policy,
    }
    provenance = {
        "handle": profile["handle"],
        "repository_version": (root / "VERSION").read_text(encoding="utf-8").strip(),
        "content_sha256": hashlib.sha256((json_text(portable) + agreement).encode()).hexdigest(),
        "source_profile": "profiles/astrobyte/profile.json",
        "source_agreement": f"profiles/astrobyte/{agreement_name}",
    }
    envelope = {"schema_version": 1, "baseline": provenance}
    return {
        **{
            Path(f"skills/{skill}/references/baseline.json"): json_text({**envelope, **portable})
            for skill in ("astrobyte-mode", "astrobyte-project-startup")
        },
        **{
            Path(f"skills/{skill}/references/working-agreement.md"): GENERATED_HEADER + agreement
            for skill in ("astrobyte-mode", "astrobyte-project-startup")
        },
        Path("skills/astrobyte-review/references/review-policy.json"): json_text({
            **envelope, "defaults": portable["defaults"],
            "review": {"instructions": agreement_section(agreement, "Review")},
        }),
        Path("skills/astrobyte-git-identity/references/git-policy.json"): json_text({
            **envelope, "git_identity": git_policy,
        }),
        **{
            Path(f"skills/{skill}/scripts/runtime_config.py"):
                (root / "scripts/runtime_config.py").read_text(encoding="utf-8")
            for skill in ("astrobyte-mode", "astrobyte-review", "astrobyte-project-startup")
        },
        **{
            Path(f"skills/{skill}/references/configuration.md"):
                (root / "skills/astrobyte-mode/references/configuration.md").read_text(encoding="utf-8")
            for skill in ("astrobyte-review", "astrobyte-project-startup")
        },
        **{
            Path(f"skills/{skill}/scripts/preferences.py"):
                (root / "scripts/preferences.py").read_text(encoding="utf-8")
            for skill in ("astrobyte-mode", "astrobyte-review", "astrobyte-git-identity", "astrobyte-project-startup")
        },
    }


def validate_resources(root: Path = REPO_ROOT) -> list[str]:
    try:
        expected = resource_contents(root)
    except (OSError, KeyError, TypeError, ValueError) as exc:
        return [f"portable baseline: {exc}"]
    errors: list[str] = []
    for relative, content in expected.items():
        try:
            actual = (root / relative).read_text(encoding="utf-8")
        except OSError as exc:
            errors.append(f"{relative}: missing or unreadable generated resource: {exc.strerror}")
            continue
        if actual != content:
            errors.append(f"{relative}: stale generated resource; run python3 scripts/portable_profile.py")
    return errors


def generate(root: Path = REPO_ROOT) -> int:
    changed = 0
    for relative, content in resource_contents(root).items():
        path = root / relative
        if path.is_file() and path.read_text(encoding="utf-8") == content:
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        changed += 1
    return changed


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Check resources without writing")
    args = parser.parse_args()
    if args.check:
        errors = validate_resources()
        if errors:
            print("\n".join(errors))
            return 1
        print("Portable baseline resources match the canonical profile.")
    else:
        print(f"Generated {generate()} changed portable baseline resources.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
