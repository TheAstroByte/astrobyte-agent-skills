#!/usr/bin/env python3
"""Generate package-local license notices from catalog provenance."""

from __future__ import annotations

import argparse
import json
from pathlib import Path


REPO_ROOT = Path(__file__).resolve().parents[1]
NOTICE_NAME = "LICENSES.txt"


def resource_contents(root: Path = REPO_ROOT) -> dict[Path, str]:
    root = root.resolve()
    catalog = json.loads((root / "catalog.json").read_text(encoding="utf-8"))
    resources: dict[Path, str] = {}
    for name, metadata in catalog["skills"].items():
        relative = Path("skills") / name / NOTICE_NAME
        if not (root / relative).resolve().is_relative_to(root / "skills"):
            raise ValueError(f"License package path escapes skills: {name}")
        if (root / relative).is_symlink():
            raise ValueError(f"{name}: license notice target must not be a symlink")
        sources = [metadata["source"], *[item.split(":", 1)[0] for item in metadata.get("derived_from", [])]]
        sections = [
            "License notices\n\nGenerated by scripts/package_licenses.py; do not edit.\n"
            "Each notice applies to material attributed to its source."
        ]
        for source in dict.fromkeys(sources):
            if source not in catalog["sources"]:
                raise ValueError(f"{name}: unknown license source {source}")
            origin = catalog["sources"][source]
            raw_path = origin.get("license_file")
            if not isinstance(raw_path, str) or not raw_path:
                raise ValueError(f"{source}: missing license_file")
            path = Path(raw_path)
            if path.is_absolute() or not (root / path).resolve().is_relative_to(root):
                raise ValueError(f"{source}: license_file escapes repository")
            text = (root / path).read_text(encoding="utf-8").strip()
            if not text:
                raise ValueError(f"{source}: empty license_file")
            revision = origin.get("commit") or origin.get("version")
            sections.append(f"Source: {origin['repository']}\nRevision: {revision}\n\n{text}")
        resources[relative] = "\n\n".join(sections) + "\n"
    return resources


def validate_licenses(root: Path = REPO_ROOT) -> list[str]:
    try:
        expected = resource_contents(root)
    except (OSError, KeyError, TypeError, ValueError) as exc:
        return [f"package licenses: {exc}"]
    errors: list[str] = []
    for relative, content in expected.items():
        path = root / relative
        if not path.is_file():
            errors.append(f"{relative}: missing license notices; run python3 scripts/package_licenses.py")
        elif path.read_text(encoding="utf-8") != content:
            errors.append(f"{relative}: stale license notices; run python3 scripts/package_licenses.py")
    return errors


def generate(root: Path = REPO_ROOT) -> int:
    changed = 0
    for relative, content in resource_contents(root).items():
        path = root / relative
        if path.is_file() and path.read_text(encoding="utf-8") == content:
            continue
        path.write_text(content, encoding="utf-8")
        changed += 1
    return changed


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Check notices without writing")
    args = parser.parse_args()
    if args.check:
        errors = validate_licenses()
        if errors:
            print("\n".join(errors))
            return 1
        print("Package license notices match catalog provenance.")
    else:
        print(f"Generated {generate()} changed package license notices.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
